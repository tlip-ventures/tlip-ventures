-- Stock & POS: stock in places (the shop and a warehouse; more later).
--
-- Every product has a count per place. The shop is the place sales come
-- from (till, wholesale, website orders, returns, voids, counts and recounts
-- all work on it as before: stock_levels stays the shop's count, kept by the
-- movement trigger). Other places hold stock too: every stock movement now
-- says where (location_id; all earlier ones were in the shop), and
-- stock_place_levels keeps each place's count. Stock goes between places by
-- transfer (two movements). Supplier deliveries arrive at the warehouse by
-- default. The website shows a product in stock while shop + other places
-- have any.

create table public.locations (
  id smallint primary key generated by default as identity,
  name text not null unique check (char_length(btrim(name)) between 1 and 40),
  -- The place sales come from. Exactly one.
  sells boolean not null default false,
  sort_order smallint not null default 0,
  created_at timestamptz not null default now()
);
create unique index locations_one_selling on public.locations (sells) where sells;

insert into public.locations (id, name, sells, sort_order) overriding system value
values (1, 'Shop', true, 1), (2, 'Warehouse', false, 2);
select setval(pg_get_serial_sequence('public.locations', 'id'), 2);

revoke all on public.locations from anon, authenticated;
grant select on public.locations to authenticated;
alter table public.locations enable row level security;
create policy "Shop users read places" on public.locations for select to authenticated
  using ((select private.is_member()));

create function private.shop_location()
returns smallint
language sql
stable
security definer
set search_path = ''
as $$
  select id from public.locations where sells;
$$;

-- Each place's count, kept only by the movement trigger.
create table public.stock_place_levels (
  variant_id uuid not null references public.product_variants (id) on delete cascade,
  location_id smallint not null references public.locations (id),
  on_hand integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (variant_id, location_id)
);
create index stock_place_levels_location_idx on public.stock_place_levels (location_id);

revoke all on public.stock_place_levels from anon, authenticated;
grant select on public.stock_place_levels to authenticated;
alter table public.stock_place_levels enable row level security;
create policy "Shop users read stock by place" on public.stock_place_levels for select to authenticated
  using ((select private.is_member()));

-- Every movement says where; all earlier ones were in the shop.
alter table public.stock_movements add column location_id smallint not null default 1 references public.locations (id);
create index stock_movements_location_idx on public.stock_movements (location_id);

insert into public.stock_place_levels (variant_id, location_id, on_hand, updated_at)
select variant_id, 1, on_hand, updated_at from public.stock_levels;

-- Earlier purchases went into the shop; new ones arrive at the warehouse unless the owner picks the shop.
alter table public.purchases add column location_id smallint not null default 1 references public.locations (id);
alter table public.purchases alter column location_id set default 2;

-- The website: in stock while all places together have any.
create function private.variant_to_website(p_variant_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_total integer;
begin
  if not private.website_stock_sync_on() then
    return;
  end if;
  select coalesce(sum(on_hand), 0) into v_total from public.stock_place_levels where variant_id = p_variant_id;
  update public.product_variants
  set in_stock = v_total > 0, stock_qty = greatest(v_total, 0)
  where id = p_variant_id and not retired
    and (in_stock is distinct from (v_total > 0) or stock_qty is distinct from greatest(v_total, 0));
end;
$$;

create or replace function private.shelf_to_website()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.variant_to_website(new.variant_id);
  return null;
end;
$$;

create or replace function private.variant_stock_from_shelf()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_total integer;
begin
  if new.retired then
    new.in_stock := false;
    new.stock_qty := 0;
  elsif private.website_stock_sync_on() then
    select coalesce(sum(on_hand), 0) into v_total from public.stock_place_levels where variant_id = new.id;
    new.in_stock := v_total > 0;
    new.stock_qty := greatest(v_total, 0);
  end if;
  return new;
end;
$$;

create or replace function private.website_stock_sync_switched()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.website_stock_sync and not old.website_stock_sync then
    update public.product_variants v
    set in_stock = coalesce(t.total, 0) > 0, stock_qty = greatest(coalesce(t.total, 0), 0)
    from (
      select pv.id, (select sum(l.on_hand) from public.stock_place_levels l where l.variant_id = pv.id) as total
      from public.product_variants pv
    ) t
    where t.id = v.id;
  end if;
  return null;
end;
$$;

-- The movement trigger: each place's count, never below zero (except an
-- imported opening figure); the shop's count also kept in stock_levels.
create or replace function private.apply_stock_movement()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_on_hand integer;
  v_shop smallint := private.shop_location();
  v_place text;
begin
  if exists (select 1 from public.product_variants v where v.id = new.variant_id and v.retired) then
    raise exception 'This stock entry is no longer used: the product''s stock is counted as one.'
      using errcode = '22023', detail = new.variant_id::text;
  end if;
  new.location_id := coalesce(new.location_id, v_shop);

  -- The shop's row first, the same order as the sales lock it.
  if new.location_id = v_shop then
    perform 1 from public.stock_levels where variant_id = new.variant_id for update;
    if not found then
      insert into public.stock_levels (variant_id) values (new.variant_id) on conflict do nothing;
      perform 1 from public.stock_levels where variant_id = new.variant_id for update;
    end if;
  end if;

  select on_hand into v_on_hand from public.stock_place_levels
  where variant_id = new.variant_id and location_id = new.location_id
  for update;
  if not found then
    insert into public.stock_place_levels (variant_id, location_id) values (new.variant_id, new.location_id) on conflict do nothing;
    select on_hand into v_on_hand from public.stock_place_levels
    where variant_id = new.variant_id and location_id = new.location_id
    for update;
  end if;

  if new.qty_change < 0 and v_on_hand + new.qty_change < 0 and new.kind <> 'opening' then
    select lower(name) into v_place from public.locations where id = new.location_id;
    raise exception 'Only % left in the %.', greatest(v_on_hand, 0), v_place
      using errcode = 'TV001', detail = new.variant_id::text;
  end if;

  new.balance_after := v_on_hand + new.qty_change;
  update public.stock_place_levels
  set on_hand = new.balance_after, updated_at = now()
  where variant_id = new.variant_id and location_id = new.location_id;

  if new.location_id = v_shop then
    -- Its own trigger brings the website up to date.
    update public.stock_levels set on_hand = new.balance_after, updated_at = now() where variant_id = new.variant_id;
  else
    perform private.variant_to_website(new.variant_id);
  end if;
  return new;
end;
$$;

-- Supplier deliveries go into the purchase's place.
create or replace function private.receive_purchase(p_purchase_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item record;
  v_place smallint;
begin
  select location_id into v_place from public.purchases where id = p_purchase_id and status = 'ordered' for update;
  if not found then
    raise exception 'This purchase is already received or cancelled.' using errcode = '22023';
  end if;

  for v_item in
    select i.variant_id, sum(i.qty)::integer as qty, max(i.unit_cost) as unit_cost
    from public.purchase_items i
    where i.purchase_id = p_purchase_id and i.variant_id is not null
    group by i.variant_id
    order by i.variant_id
  loop
    insert into public.stock_movements (variant_id, qty_change, kind, purchase_id, location_id)
    values (v_item.variant_id, v_item.qty, 'purchase', p_purchase_id, v_place);

    insert into public.variant_costs (variant_id, cost_price, updated_by)
    values (v_item.variant_id, v_item.unit_cost, auth.uid())
    on conflict (variant_id) do update
      set cost_price = excluded.cost_price, updated_by = excluded.updated_by;
  end loop;

  update public.purchases
  set status = 'received', received_at = now(), received_by = auth.uid()
  where id = p_purchase_id;
end;
$$;

-- A purchase says where it arrives (p.location_id; the warehouse when left out).
create or replace function public.pos_save_purchase(p jsonb)
returns table(purchase_id uuid, code text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id uuid;
  v_code text;
  v_total integer;
  v_lines integer;
  v_found integer;
  v_amount integer := (p -> 'payment' ->> 'amount')::integer;
  v_place smallint := coalesce((p ->> 'location_id')::smallint, 2);
begin
  if not private.is_owner() then
    raise exception 'Only the owner can record purchases.' using errcode = '42501';
  end if;
  if not exists (select 1 from public.suppliers where id = (p ->> 'supplier_id')::uuid) then
    raise exception 'Choose the supplier.' using errcode = '22023';
  end if;
  if not exists (select 1 from public.locations where id = v_place) then
    raise exception 'Choose where the delivery arrives.' using errcode = '22023';
  end if;
  if jsonb_typeof(p -> 'lines') is distinct from 'array' or jsonb_array_length(p -> 'lines') = 0 then
    raise exception 'Add at least one item.' using errcode = '22023';
  end if;
  if exists (
    select 1 from jsonb_to_recordset(p -> 'lines') as l (variant_id uuid, qty integer, unit_cost integer)
    where l.variant_id is null or l.qty is null or l.qty < 1 or l.qty > 100000 or l.unit_cost is null or l.unit_cost < 0
  ) then
    raise exception 'Each item needs a quantity and a cost.' using errcode = '22023';
  end if;

  select count(*), count(v.id), coalesce(sum(l.qty * l.unit_cost), 0)
  into v_lines, v_found, v_total
  from jsonb_to_recordset(p -> 'lines') as l (variant_id uuid, qty integer, unit_cost integer)
  left join public.product_variants v on v.id = l.variant_id and not v.retired;
  if v_found <> v_lines then
    raise exception 'An item on this purchase is no longer in the catalogue.' using errcode = 'P0002';
  end if;
  if v_amount is not null and (v_amount < 0 or v_amount > v_total) then
    raise exception 'The amount paid can''t be more than the purchase.' using errcode = '22023';
  end if;

  insert into public.purchases (supplier_id, total, note, location_id)
  values ((p ->> 'supplier_id')::uuid, v_total, nullif(btrim(p ->> 'note'), ''), v_place)
  returning id, purchases.code into v_id, v_code;

  insert into public.purchase_items (purchase_id, variant_id, product_name, option_values, unit_cost, qty, line_total)
  select v_id, l.variant_id, pr.name, null, l.unit_cost, l.qty, l.unit_cost * l.qty
  from rows from (jsonb_to_recordset(p -> 'lines') as (variant_id uuid, qty integer, unit_cost integer))
    with ordinality as l (variant_id, qty, unit_cost, n)
  join public.product_variants v on v.id = l.variant_id
  join public.products pr on pr.id = v.product_id
  order by l.n;

  if coalesce((p ->> 'received')::boolean, false) then
    perform private.receive_purchase(v_id);
  end if;

  if coalesce(v_amount, 0) > 0 then
    insert into public.purchase_payments (purchase_id, method, amount)
    values (v_id, (p -> 'payment' ->> 'method')::public.payment_method, v_amount);
  end if;

  return query select v_id, v_code;
end;
$$;

-- Move stock between places (owner, or staff who may count and adjust stock).
create function public.pos_move_stock(p_variant_id uuid, p_from smallint, p_to smallint, p_qty integer, p_note text default null)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_from text;
  v_to text;
  v_note text := left(nullif(btrim(p_note), ''), 200);
  v_left integer;
  v_now integer;
begin
  if not private.can_adjust_stock() then
    raise exception 'You are not allowed to move stock. Ask the owner.' using errcode = '42501';
  end if;
  if p_qty is null or p_qty < 1 or p_qty > 100000 then
    raise exception 'Enter how many to move (1 or more).' using errcode = '22023';
  end if;
  select name into v_from from public.locations where id = p_from;
  select name into v_to from public.locations where id = p_to;
  if v_from is null or v_to is null or p_from = p_to then
    raise exception 'Choose two different places.' using errcode = '22023';
  end if;
  if not exists (select 1 from public.product_variants where id = p_variant_id and not retired) then
    raise exception 'This product no longer exists.' using errcode = 'P0002';
  end if;
  -- The shop's row first, the same order as the sales lock it.
  perform 1 from public.stock_levels where variant_id = p_variant_id for update;

  insert into public.stock_movements (variant_id, qty_change, kind, reason, location_id)
  values (p_variant_id, -p_qty, 'transfer', concat_ws(' · ', 'To ' || v_to, v_note), p_from)
  returning balance_after into v_left;
  insert into public.stock_movements (variant_id, qty_change, kind, reason, location_id)
  values (p_variant_id, p_qty, 'transfer', concat_ws(' · ', 'From ' || v_from, v_note), p_to)
  returning balance_after into v_now;
  return json_build_object('from_left', v_left, 'to_now', v_now);
end;
$$;

-- Recount and adjust in any place (the earlier versions are the shop's).
create function public.pos_recount_at(p_variant_id uuid, p_location smallint, p_counted integer, p_reason text default null)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_on_hand integer;
  v_change integer;
begin
  if not private.can_adjust_stock() then
    raise exception 'You are not allowed to count or adjust stock.' using errcode = '42501';
  end if;
  if p_counted is null or p_counted < 0 or p_counted > 100000 then
    raise exception 'Enter how many are there (0 or more).' using errcode = '22023';
  end if;
  if not exists (select 1 from public.locations where id = p_location) then
    raise exception 'Choose the place.' using errcode = '22023';
  end if;
  if not exists (select 1 from public.product_variants where id = p_variant_id and not retired) then
    raise exception 'This product no longer exists.' using errcode = 'P0002';
  end if;
  if p_location = private.shop_location() then
    perform 1 from public.stock_levels where variant_id = p_variant_id for update;
  end if;
  select on_hand into v_on_hand from public.stock_place_levels
  where variant_id = p_variant_id and location_id = p_location for update;
  v_change := p_counted - coalesce(v_on_hand, 0);
  if v_change <> 0 then
    insert into public.stock_movements (variant_id, qty_change, kind, reason, location_id)
    values (p_variant_id, v_change, 'count', coalesce(nullif(btrim(p_reason), ''), 'Recount'), p_location);
  end if;
  return v_change;
end;
$$;

create function public.pos_adjust_stock_at(p_variant_id uuid, p_location smallint, p_change integer, p_reason text)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_balance integer;
begin
  if not private.can_adjust_stock() then
    raise exception 'You are not allowed to count or adjust stock.' using errcode = '42501';
  end if;
  if p_change is null or p_change = 0 or abs(p_change) > 100000 then
    raise exception 'Enter how many to add or take away.' using errcode = '22023';
  end if;
  if char_length(btrim(coalesce(p_reason, ''))) = 0 then
    raise exception 'Say why the stock is changing.' using errcode = '22023';
  end if;
  if not exists (select 1 from public.locations where id = p_location) then
    raise exception 'Choose the place.' using errcode = '22023';
  end if;
  if not exists (select 1 from public.product_variants where id = p_variant_id and not retired) then
    raise exception 'This product no longer exists.' using errcode = 'P0002';
  end if;
  insert into public.stock_movements (variant_id, qty_change, kind, reason, location_id)
  values (p_variant_id, p_change, 'adjustment', btrim(p_reason), p_location)
  returning balance_after into v_balance;
  return v_balance;
end;
$$;

-- Stock value (owner): every place.
create or replace function public.pos_stock_summary()
returns json
language sql
stable
security invoker
set search_path = ''
as $$
  select json_build_object(
    'products', (select count(*) from public.products),
    'low', count(*) filter (where r.stock_state in ('low', 'out')),
    'recount', count(*) filter (where r.stock_state = 'recount'),
    'value', case when (select private.is_owner()) then (
      select coalesce(sum(greatest(s.on_hand, 0)::bigint * c.cost_price), 0)
      from public.stock_place_levels s
      join public.variant_costs c on c.variant_id = s.variant_id
    ) end
  )
  from public.pos_stock_rows r;
$$;

-- Products: the shop's count (on_hand, what sells) and the other places'.
create or replace view public.pos_stock_rows
with (security_invoker = true)
as
select
  v.id as variant_id,
  p.id as product_id,
  p.name as product_name,
  nullif(concat_ws(' / ', v.option1_value, v.option2_value), '') as option_label,
  v.sku,
  v.barcode,
  coalesce(v.price_override, p.price) as price,
  p.is_active as on_website,
  v.reorder_level,
  coalesce(s.on_hand, 0) as on_hand,
  case
    when coalesce(s.on_hand, 0) < 0 then 'recount'
    when coalesce(s.on_hand, 0) = 0 then 'out'
    when s.on_hand <= v.reorder_level then 'low'
    else 'ok'
  end as stock_state,
  case
    when coalesce(s.on_hand, 0) < 0 then 0
    when coalesce(s.on_hand, 0) = 0 then 1
    when s.on_hand <= v.reorder_level then 2
    else 3
  end as state_rank,
  cat.category_id,
  cat.category_name,
  cat.top_category_id,
  cat.top_category_name,
  img.url as image_url,
  p.updated_at,
  p.option1_name as choice_name,
  p.choices,
  w.price as wholesale_price,
  coalesce(other.on_hand, 0) as warehouse_on_hand,
  coalesce(s.on_hand, 0) + coalesce(other.on_hand, 0) as total_on_hand
from public.product_variants v
join public.products p on p.id = v.product_id
left join public.stock_levels s on s.variant_id = v.id
left join public.product_wholesale_prices w on w.product_id = p.id
left join lateral (
  select sum(l.on_hand)::integer as on_hand
  from public.stock_place_levels l
  join public.locations loc on loc.id = l.location_id
  where l.variant_id = v.id and not loc.sells
) other on true
left join lateral (
  select c.id as category_id, c.name as category_name,
    coalesce(parent.id, c.id) as top_category_id, coalesce(parent.name, c.name) as top_category_name
  from public.product_categories pc
  join public.categories c on c.id = pc.category_id
  left join public.categories parent on parent.id = c.parent_id
  where pc.product_id = p.id
  order by c.parent_id is null, coalesce(parent.sort_order, c.sort_order), c.sort_order, c.name
  limit 1
) cat on true
left join lateral (
  select i.url from public.product_images i where i.product_id = p.id order by i.sort_order limit 1
) img on true
where not v.retired;

-- Reports' stock value and units: every place. Edits the live function in
-- place (it changes often), and stops if the text it looks for has moved.
do $m$
declare
  v_def text := pg_get_functiondef('public.pos_report_overview(timestamptz, timestamptz)'::regprocedure);
  v_old text := 'select r.on_hand, r.price, vc.cost_price, r.stock_state';
  v_new text := 'select r.total_on_hand as on_hand, r.price, vc.cost_price, r.stock_state';
begin
  if strpos(v_def, v_old) = 0 then
    raise exception 'pos_report_overview has changed: its stock lines were not found.';
  end if;
  execute replace(v_def, v_old, v_new);
end
$m$;

-- The ledger check: each place's count against its movements, and the
-- shop's count kept in stock_levels against the shop's place count.
create or replace function private.stock_drift()
returns table(variant_id uuid, on_hand integer, movements_total bigint)
language sql
stable
security definer
set search_path = ''
as $$
  select l.variant_id, l.on_hand, coalesce(m.total, 0)
  from public.stock_place_levels l
  left join (
    select sm.variant_id, sm.location_id, sum(sm.qty_change) as total from public.stock_movements sm group by 1, 2
  ) m on m.variant_id = l.variant_id and m.location_id = l.location_id
  where l.on_hand <> coalesce(m.total, 0)
  union all
  select s.variant_id, s.on_hand, l.on_hand::bigint
  from public.stock_levels s
  join public.stock_place_levels l on l.variant_id = s.variant_id and l.location_id = private.shop_location()
  where s.on_hand <> l.on_hand;
$$;

