-- Stock & POS: expenses (owner only). The shop's running costs (rent,
-- salaries, riders, transport, electricity…), each with the day, the kind
-- of expense, the amount in pesewas and how it was paid (cash, MoMo, bank).
-- Reports take them off the profit on goods to give the real profit.
-- An expense is never removed: a wrong one is cancelled with a reason.

create table public.expense_categories (
  id smallint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 40),
  sort_order smallint not null default 100,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index expense_categories_name_idx on public.expense_categories (lower(btrim(name)));

insert into public.expense_categories (name, sort_order) values
  ('Rent', 1),
  ('Salaries and wages', 2),
  ('Riders and delivery', 3),
  ('Transport', 4),
  ('Electricity and water', 5),
  ('Phone and internet', 6),
  ('Packaging', 7),
  ('Repairs and maintenance', 8),
  ('Marketing and adverts', 9),
  ('Bank and MoMo charges', 10),
  ('Loan repayment', 11),
  ('Taxes and fees', 12),
  ('Other', 99);

create table public.expenses (
  id uuid primary key default gen_random_uuid(),
  spent_on date not null,
  category_id smallint not null references public.expense_categories (id),
  amount integer not null check (amount > 0 and amount <= 100000000),
  method public.payment_method not null,
  payee text check (payee is null or char_length(payee) <= 100),
  note text check (note is null or char_length(note) <= 300),
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_by uuid,
  updated_at timestamptz,
  cancelled_at timestamptz,
  cancelled_by uuid,
  cancel_reason text check (cancel_reason is null or char_length(cancel_reason) <= 300)
);
create index expenses_spent_on_idx on public.expenses (spent_on desc);
create index expenses_category_idx on public.expenses (category_id);

revoke all on public.expense_categories, public.expenses from anon, authenticated;
grant select on public.expense_categories, public.expenses to authenticated;
alter table public.expense_categories enable row level security;
alter table public.expenses enable row level security;
create policy "Owner reads expense kinds" on public.expense_categories for select to authenticated using ((select private.is_owner()));
create policy "Owner reads expenses" on public.expenses for select to authenticated using ((select private.is_owner()));

-- Record a new expense, or change one (p.id). Not after today; a cancelled
-- one can't be changed.
create function public.pos_save_expense(p jsonb)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id uuid := nullif(p ->> 'id', '')::uuid;
  v_day date := (p ->> 'spent_on')::date;
  v_category smallint := (p ->> 'category_id')::smallint;
  v_amount integer := (p ->> 'amount')::integer;
  v_method text := p ->> 'method';
  v_payee text := left(nullif(btrim(coalesce(p ->> 'payee', '')), ''), 100);
  v_note text := left(nullif(btrim(coalesce(p ->> 'note', '')), ''), 300);
begin
  if not private.is_owner() then
    raise exception 'Only the owner can record expenses.' using errcode = '42501';
  end if;
  if v_day is null or v_day > (now() at time zone 'utc')::date then
    raise exception 'Pick the day it was paid (today or earlier).' using errcode = '22023';
  end if;
  if v_amount is null or v_amount <= 0 or v_amount > 100000000 then
    raise exception 'Enter the amount paid.' using errcode = '22023';
  end if;
  if v_method is null or v_method not in ('cash', 'momo', 'bank') then
    raise exception 'Choose how it was paid.' using errcode = '22023';
  end if;
  if v_id is null then
    if not exists (select 1 from public.expense_categories where id = v_category and is_active) then
      raise exception 'Choose the kind of expense.' using errcode = '22023';
    end if;
    insert into public.expenses (spent_on, category_id, amount, method, payee, note)
    values (v_day, v_category, v_amount, v_method::public.payment_method, v_payee, v_note)
    returning id into v_id;
  else
    if not exists (select 1 from public.expense_categories where id = v_category) then
      raise exception 'Choose the kind of expense.' using errcode = '22023';
    end if;
    update public.expenses
    set spent_on = v_day, category_id = v_category, amount = v_amount, method = v_method::public.payment_method,
        payee = v_payee, note = v_note, updated_by = auth.uid(), updated_at = now()
    where id = v_id and cancelled_at is null;
    if not found then
      raise exception 'This expense was cancelled or no longer exists.' using errcode = '22023';
    end if;
  end if;
  return v_id;
end;
$$;

-- Cancel a wrong expense (kept, with the reason; no longer counted).
create function public.pos_cancel_expense(p_id uuid, p_reason text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_owner() then
    raise exception 'Only the owner can cancel expenses.' using errcode = '42501';
  end if;
  if char_length(btrim(coalesce(p_reason, ''))) = 0 then
    raise exception 'Say why it is cancelled.' using errcode = '22023';
  end if;
  update public.expenses
  set cancelled_at = now(), cancelled_by = auth.uid(), cancel_reason = left(btrim(p_reason), 300)
  where id = p_id and cancelled_at is null;
  if not found then
    raise exception 'This expense is already cancelled.' using errcode = '22023';
  end if;
end;
$$;

-- Add a kind of expense (p_id null), or rename / hide / show one.
create function public.pos_save_expense_category(p_id smallint, p_name text, p_is_active boolean default true)
returns smallint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id smallint := p_id;
  v_name text := btrim(coalesce(p_name, ''));
begin
  if not private.is_owner() then
    raise exception 'Only the owner can change the kinds of expense.' using errcode = '42501';
  end if;
  if char_length(v_name) not between 1 and 40 then
    raise exception 'Give it a name (up to 40 characters).' using errcode = '22023';
  end if;
  if exists (select 1 from public.expense_categories where lower(btrim(name)) = lower(v_name) and id is distinct from p_id) then
    raise exception 'There is already a kind called %.', v_name using errcode = '23505';
  end if;
  if v_id is null then
    insert into public.expense_categories (name, is_active) values (v_name, coalesce(p_is_active, true)) returning id into v_id;
  else
    update public.expense_categories set name = v_name, is_active = coalesce(p_is_active, true) where id = v_id;
    if not found then
      raise exception 'This kind of expense no longer exists.' using errcode = 'P0002';
    end if;
  end if;
  return v_id;
end;
$$;

-- Expenses for a stretch of time (days from p_from up to p_to, Ghana time =
-- UTC): the total, by kind, by way of paying, and the number of expenses.
-- Runs as the caller: only the owner sees anything.
create function public.pos_expense_summary(p_from timestamptz, p_to timestamptz)
returns json
language sql
stable
security invoker
set search_path = ''
as $$
  with e as (
    select x.amount, x.method::text as method, c.name as category, c.sort_order
    from public.expenses x
    join public.expense_categories c on c.id = x.category_id
    where x.cancelled_at is null
      and x.spent_on >= (p_from at time zone 'utc')::date
      and x.spent_on < (p_to at time zone 'utc')::date
  )
  select json_build_object(
    'total', coalesce((select sum(amount) from e), 0),
    'count', (select count(*) from e),
    'by_method', json_build_object(
      'cash', coalesce((select sum(amount) from e where method = 'cash'), 0),
      'momo', coalesce((select sum(amount) from e where method = 'momo'), 0),
      'bank', coalesce((select sum(amount) from e where method = 'bank'), 0)
    ),
    'by_category', coalesce((
      select json_agg(json_build_object('name', category, 'total', total) order by total desc, category)
      from (select category, sum(amount) as total from e group by category) k
    ), '[]'::json)
  );
$$;

-- Expense totals for consecutive stretches (the 12-month table): bounds are
-- n + 1 times for n stretches.
create function public.pos_expense_totals(p_bounds timestamptz[])
returns integer[]
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce(array_agg(coalesce(t.total, 0)::integer order by b.i), '{}')
  from generate_series(1, greatest(array_length(p_bounds, 1) - 1, 0)) as b (i)
  left join lateral (
    select sum(x.amount) as total
    from public.expenses x
    where x.cancelled_at is null
      and x.spent_on >= (p_bounds[b.i] at time zone 'utc')::date
      and x.spent_on < (p_bounds[b.i + 1] at time zone 'utc')::date
  ) t on true;
$$;

revoke execute on function
